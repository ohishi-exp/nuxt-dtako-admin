-- 社員属性に給与区分 (`SHAIN3.KKUBUN`) を足す (Refs #429)。
--
-- なぜ: 給与比較の「基本給(計算)」は `【補助】基本単価 × 稼働日数` で出しており、
-- **単価を日額と仮定**している。日給者以外ではこの式が意味を持たず、#424 (PR-D) で
-- 本社事務員が給与比較に出るようになった結果、月給者の基本給(計算)が 2,640,000 円
-- (実際の基本給は 165,000 円) と桁外れに表示された。
--
-- **既存の `pay_scheme` では判定できない**: あれは `SHOZOKU.TAIKEI` (部署の体系) を
-- 「体系N」とラベル化したもので、給与区分とは**独立した軸**。実機調査 (2026-07-26、
-- KYDATA0200_126C) で、同じ TAIKEI=1 (乗務員) でも月給/日給/時給が混在し、
-- TAIKEI=2 (事務員) にも時給者がいることが確認されている。よって `pay_scheme` は
-- 消さずに残し、別列として持つ。
--
-- 値 (`SHAIN3.KKUBUN`、給与大臣の社員情報画面「2 給与区分」の並び順):
--   1 = 月給 / 2 = 日給 / 3 = 時給 / 4 = その他 (実データ未出現)
--   NULL = 未取得 (取り込み前の既存行)。0 = 給与大臣側で未設定
--
-- 既存行は NULL のままになる。「給与DBから取り込み」を再実行すると同じ
-- `effective_from` の行が UPDATE されて埋まる (migration 0010 と同じ振る舞い)。
-- 埋まるまでは区分が引けない = 基本給(計算)を出さない安全側に倒れるので、
-- 月給者に無意味な差が出る現状より悪くなることはない。
ALTER TABLE employee_attrs ADD COLUMN pay_kubun INTEGER;
